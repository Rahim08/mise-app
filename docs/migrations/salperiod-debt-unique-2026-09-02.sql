-- =============================================================================
-- Защита от гонки в долг-леджере ЗП (2026-09-02).
--
-- Найдено в проде (ресторан SO): 26 строк долга в shift_expenses вместо 13 — КАЖДЫЙ
-- сотрудник задвоен ровно один раз, вставки в течение 17 секунд (2026-08-31 23:58:37 →
-- 23:58:54). Причина: syncLedger (app/manager/tabs-salary.tsx) и его iOS-порт
-- (ManagerSalary.swift, MISE-001) делают read-then-write без атомарности — сначала
-- SELECT «есть ли уже такая строка», потом INSERT. Два параллельных запуска loadDebt()
-- (два открытых окна/устройства, оба тянут вкладку Manager→Зарплата примерно одновременно)
-- оба видят «нет строки» до того, как первый успевает вставить — оба вставляют.
--
-- На инкассацию дубли ещё не повлияли (is_paid=false у всех, ни одна не оплачена) — но
-- если бы владелец закрыл обе копии долга каждого сотрудника через экран «Долги», settle_debts
-- списал бы вдвое больше настоящего долга из инкассации.
--
-- Фикс — не в коде (симптом устранять бессмысленно, гонка может прийти с любой стороны:
-- ретрай, два устройства, StrictMode), а в БД: уникальный индекс, который физически не
-- даёт создать вторую открытую строку долга для той же пары сотрудник/период. Партиальный —
-- задевает только SALPERIOD-леджер, обычные расходные/экстра-долги (свободный note,
-- законно могут повторяться для одного сотрудника) не затронуты.
--
-- После этой миграции проигравшая сторона гонки просто получит 23505 (Duplicate entry —
-- уже промаплено в app/api/db/route.ts PG_ERROR_MESSAGES) на INSERT; код syncLedger/
-- syncSalaryLedger уже не проверяет error на этой вставке (как и остальные вызовы в файле),
-- так что это тихо не пройдёт — ровно то поведение, которое нужно (в БД остаётся одна
-- строка, кто бы её ни вставил).
-- =============================================================================

CREATE UNIQUE INDEX IF NOT EXISTS uniq_salperiod_debt
  ON shift_expenses (restaurant_id, employee_id, note)
  WHERE note LIKE 'SALPERIOD:%';
