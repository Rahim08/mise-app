-- =============================================================================
-- salary_advances.period — юзер-фидбок 2026-08-15: месяц ЗП, к которому относится аванс,
-- раньше выводился из поля date (день, когда деньги реально снимаются из кассы). Баг:
-- аванс, взятый в июле датой на август ("возьму сегодня в счёт августовской ЗП"), уходил
-- в зарплату августа вместо июля — юзер жал «добавить», стоя на экране июля, ждал списание
-- по июльской ЗП.
--
-- Раздельные смыслы:
--   date   — день физического списания из кассы/инкассации (не меняется)
--   period — месяц ЗП, к которому относится аванс = месяц ЭКРАНА (viewMonth), на котором
--            нажали «добавить аванс», первое число (YYYY-MM-01), как salary_payments.period
--
-- ПРИМЕНИТЬ В SUPABASE ДО деплоя нового кода (app/manager/tabs-salary.tsx,
-- ManagerSalary.swift) — иначе insert без period упадёт после ALTER COLUMN ... SET NOT NULL.
-- =============================================================================

ALTER TABLE salary_advances ADD COLUMN IF NOT EXISTS period date;

-- Бэкафилл существующих строк: месяц выводим из date (это лучшее приближение задним числом —
-- для старых записей period и date-месяц совпадали, проблема появляется только начиная с
-- этого фикса, когда date можно указывать вне текущего месяца).
UPDATE salary_advances SET period = date_trunc('month', date)::date WHERE period IS NULL;

ALTER TABLE salary_advances ALTER COLUMN period SET NOT NULL;
